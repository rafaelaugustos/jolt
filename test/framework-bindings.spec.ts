import { describe, it, expect } from 'vitest'
import { animateBinding, pressBinding } from '../src/frameworks/native-binding.js'
import { createView, driver } from './helpers.js'

describe('native framework ownership', () => {
  it('does not restart equal inline animation/press objects on a framework render', () => {
    const view = createView()
    const animation = animateBinding(view, [{ x: 100 }, { duration: 600 }])
    animation.update([{ x: 100 }, { duration: 600 }])
    expect(driver.played).toHaveLength(1)
    const feedback = pressBinding(view, { scale: 0.95 })
    view.touch('down')
    const count = driver.played.length
    feedback.update({ scale: 0.95 })
    expect(driver.played).toHaveLength(count)
    animation.update([{ x: 100 }, { duration: 600 }], true)
    expect(driver.played.length).toBeGreaterThan(count)
    feedback.destroy()
    animation.destroy()
  })
  it('cleans up lifecycle listeners when initial animation validation fails', () => {
    const view = createView()
    expect(() => animateBinding(view, { x: NaN })).toThrow()
    expect(view.listenerCount('loaded')).toBe(0)
    expect(view.listenerCount('unloaded')).toBe(0)
    expect(() => pressBinding(view, { scale: NaN })).toThrow()
    expect(view.listenerCount('loaded')).toBe(0)
    expect(view.listenerCount('unloaded')).toBe(0)
  })
  it('defers until native load, applies only the latest pending input and destroys its work', () => {
    const view = createView().unload()
    const binding = animateBinding({ nativeView: view }, { x: 100 })
    binding.update({ x: 200 })
    expect(driver.played).toHaveLength(0)
    view.load()
    expect(driver.played).toHaveLength(1)
    expect(driver.played[0]!.track.to).toBe(200)
    binding.destroy()
    binding.destroy()
    expect(driver.played[0]!.stopped).toBe(true)
    view.notify({ eventName: 'loaded', object: view })
    expect(driver.played).toHaveLength(1)
  })
  it('holds on unload, resumes, and applies changes made while unloaded', () => {
    const view = createView()
    const binding = animateBinding({ nativeElement: view }, { x: 100 })
    view.unload()
    view.notify({ eventName: 'unloaded', object: view })
    expect(binding.current!.paused).toBe(true)
    binding.update({ x: 180 })
    expect(driver.played).toHaveLength(1)
    view.load()
    expect(binding.current!.paused).toBe(false)
    expect(driver.played.at(-1)!.track.to).toBe(180)
    binding.update(undefined)
    expect(binding.current).toBeUndefined()
    binding.destroy()
  })
  it('owns press separately from application playback and removes feedback on teardown', () => {
    const view = createView()
    const animation = animateBinding(view, { x: 100 })
    const feedback = pressBinding({ nativeView: view }, { scale: 0.95 })
    view.touch('down')
    feedback.destroy()
    expect(animation.current!.paused).toBe(false)
    expect(driver.played[0]!.stopped).toBe(false)
    const count = driver.played.length
    view.touch('down')
    expect(driver.played).toHaveLength(count)
    animation.destroy()
  })
})
