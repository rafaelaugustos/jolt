import XCTest

@testable import JoltSwiftUI

final class EffectResourceTests: XCTestCase {
  @MainActor func testShimmerRunsOnlyWhileShownActiveAndMoving() async throws {
    let clock = JoltClock.testClock()
    let scope = JoltScope()
    let shimmer = try scope.retain(JoltShimmer(clock: clock))
    XCTAssertEqual(shimmer.duration, 1500)
    XCTAssertEqual(shimmer.state, .idle)
    XCTAssertEqual(clock.activeCount, 0)
    let view = UUID()
    shimmer.link(view, active: true, reduced: false)
    XCTAssertEqual(shimmer.state, .running)
    XCTAssertEqual(clock.activeCount, 1)
    try clock.advance(by: 375)
    XCTAssertEqual(shimmer.elapsed, 375, accuracy: 1e-9)
    XCTAssertEqual(shimmer.offset, -0.5, accuracy: 1e-9)
    shimmer.link(view, active: false, reduced: false)
    XCTAssertEqual(shimmer.state, .suspended)
    XCTAssertEqual(clock.activeCount, 0)
    try clock.advance(by: 1000)
    XCTAssertEqual(shimmer.elapsed, 375, accuracy: 1e-9)
    shimmer.link(view, active: true, reduced: false)
    try clock.advance(by: 1500)
    XCTAssertEqual(shimmer.elapsed, 375, accuracy: 1e-9)
    scope.suspend()
    XCTAssertEqual(clock.activeCount, 0)
    XCTAssertEqual(shimmer.state, .suspended)
    shimmer.pause()
    scope.resume()
    XCTAssertEqual(clock.activeCount, 0)
    XCTAssertEqual(shimmer.state, .paused)
    shimmer.play()
    XCTAssertEqual(clock.activeCount, 1)
    shimmer.link(view, active: true, reduced: true)
    XCTAssertEqual(clock.activeCount, 0)
    XCTAssertEqual(shimmer.elapsed, 0)
    XCTAssertEqual(shimmer.offset, -1)
    shimmer.link(view, active: true, reduced: false)
    XCTAssertEqual(clock.activeCount, 1)
    shimmer.unlink(view)
    XCTAssertEqual(clock.activeCount, 0)
    XCTAssertEqual(shimmer.viewCount, 0)
    scope.dispose()
    XCTAssertTrue(shimmer.disposed)
    shimmer.play()
    shimmer.resume()
    shimmer.link(view, active: true, reduced: false)
    XCTAssertEqual(clock.activeCount, 0)
    XCTAssertEqual(shimmer.state, .disposed)
  }
  @MainActor func testLoopsShareOneClockAcrossViewsAndStopForSystemReducedMotion() async throws {
    let clock = JoltClock.testClock()
    let loader = try JoltLoader(.ring, clock: clock)
    let first = UUID()
    let second = UUID()
    loader.link(first, active: true, reduced: false)
    loader.link(second, active: true, reduced: false)
    XCTAssertEqual(clock.activeCount, 1)
    try clock.advance(by: 1300)
    XCTAssertEqual(loader.elapsed, 100, accuracy: 1e-9)
    loader.unlink(first)
    XCTAssertEqual(clock.activeCount, 1)
    let moving = loader.items(width: 80, height: 60)
    XCTAssertEqual(moving.count, 12)
    XCTAssertEqual(moving[1].opacity, 1, accuracy: 1e-9)
    XCTAssertEqual(moving[0].width, 48 * 0.16, accuracy: 1e-12)
    XCTAssertEqual(loader.items(width: 20, height: 60)[0].width, 20 * 0.16, accuracy: 1e-12)
    XCTAssertTrue(
      loader.items(width: 80, height: 60, reducedMotion: true).allSatisfy {
        $0.opacity == 0.35
      })
    clock.testingReducedMotion = true
    try clock.advance(by: 16)
    XCTAssertEqual(clock.activeCount, 0)
    XCTAssertEqual(loader.elapsed, 0)
    loader.link(second, active: true, reduced: false)
    XCTAssertEqual(clock.activeCount, 0)
    clock.testingReducedMotion = false
    loader.link(second, active: true, reduced: false)
    XCTAssertEqual(clock.activeCount, 1)
    loader.dispose()
    XCTAssertEqual(clock.activeCount, 0)
    XCTAssertEqual(loader.items(width: 80, height: 80), [])
    loader.dispose()
  }
