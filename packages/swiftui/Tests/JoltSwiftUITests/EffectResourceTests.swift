  @MainActor func testRevealInterruptsReversesAndRemovesItsClip() async throws {
    let clock = JoltClock.testClock()
    let reveal = JoltReveal(revealed: false, clock: clock)
    let view = UUID()
    var results: [String] = []
    try reveal.reveal(from: JoltPoint(20, 30)) { results.append("reveal \($0)") }
    XCTAssertEqual(reveal.phase, .revealing)
    XCTAssertFalse(reveal.interactive)
    XCTAssertEqual(clock.activeCount, 0)
    reveal.resize(width: 200, height: 100)
    XCTAssertEqual(reveal.circle?.radius, 0)
    reveal.link(view, active: true, reduced: false)
    XCTAssertEqual(clock.activeCount, 1)
    XCTAssertEqual(reveal.state, .running)
    try clock.advance(by: 200)
    let far = hypot(180.0, 70.0)
    XCTAssertEqual(reveal.circle?.x, 20)
    XCTAssertEqual(reveal.circle?.radius ?? 0, far / 2, accuracy: 1e-6)
    XCTAssertThrowsError(try reveal.conceal(duration: .nan))
    XCTAssertThrowsError(try reveal.conceal(duration: 60_001))
    XCTAssertEqual(reveal.phase, .revealing)
    XCTAssertEqual(clock.activeCount, 1)
    try reveal.conceal(duration: 400) { results.append("conceal \($0)") }
    XCTAssertEqual(results, ["reveal false"])
    XCTAssertEqual(reveal.phase, .concealing)
    XCTAssertEqual(reveal.circle?.radius ?? 0, far / 2, accuracy: 1e-6)
    XCTAssertEqual(reveal.circle?.y, 30)
    try clock.advance(by: 200)
    XCTAssertEqual(reveal.circle?.radius ?? 0, far / 4, accuracy: 1e-6)
    try clock.advance(by: 200)
    XCTAssertEqual(reveal.phase, .concealed)
    XCTAssertNil(reveal.circle)
    XCTAssertEqual(results, ["reveal false", "conceal true"])
    XCTAssertEqual(clock.activeCount, 0)
    try reveal.conceal { results.append("again \($0)") }
    XCTAssertEqual(results.last, "again true")
    try reveal.reveal()
    try clock.advance(by: 400)
    XCTAssertEqual(reveal.phase, .revealed)
    XCTAssertTrue(reveal.interactive)
    XCTAssertNil(reveal.circle)
    XCTAssertEqual(reveal.state, .completed)
    XCTAssertEqual(clock.activeCount, 0)
  }
  @MainActor func testRevealHoldsOffScreenCancelsToItsStartAndSettlesUnderReducedMotion()
    async throws
  {
    let clock = JoltClock.testClock()
    let scope = JoltScope()
    let reveal = try scope.retain(JoltReveal(revealed: false, clock: clock))
    let view = UUID()
    reveal.resize(width: 100, height: 100)
    reveal.link(view, active: true, reduced: false)
    try reveal.reveal(duration: 1000)
    try clock.advance(by: 500)
    let held = reveal.circle
    reveal.unlink(view)
    XCTAssertEqual(clock.activeCount, 0)
    XCTAssertEqual(reveal.state, .suspended)
    try clock.advance(by: 2000)
    XCTAssertEqual(reveal.circle, held)
    reveal.link(view, active: true, reduced: false)
    scope.suspend()
    XCTAssertEqual(clock.activeCount, 0)
    reveal.pause()
    scope.resume()
    XCTAssertEqual(reveal.state, .paused)
    reveal.play()
    XCTAssertEqual(clock.activeCount, 1)
    try reveal.conceal()
    try clock.advance(by: 100)
    reveal.cancel()
    XCTAssertEqual(reveal.phase, .concealed)
    XCTAssertEqual(reveal.state, .cancelled)
    XCTAssertEqual(clock.activeCount, 0)
    var finished: Bool?
    try reveal.reveal(reducedMotion: true) { finished = $0 }
    XCTAssertEqual(finished, true)
    XCTAssertEqual(reveal.phase, .revealed)
    try reveal.conceal(duration: 0)
    XCTAssertEqual(reveal.phase, .concealed)
    try reveal.reveal()
    reveal.link(view, active: true, reduced: true)
    XCTAssertEqual(reveal.phase, .revealed)
    reveal.link(view, active: true, reduced: false)
    clock.testingReducedMotion = true
    try reveal.conceal()
    XCTAssertEqual(reveal.phase, .concealed)
    clock.testingReducedMotion = false
    try reveal.reveal()
    XCTAssertEqual(clock.activeCount, 1)
    scope.dispose()
    XCTAssertTrue(reveal.disposed)
    XCTAssertEqual(reveal.phase, .concealed)
    XCTAssertEqual(reveal.state, .disposed)
    XCTAssertEqual(clock.activeCount, 0)
    XCTAssertThrowsError(try reveal.reveal())
    reveal.play()
    reveal.link(view, active: true, reduced: false)
    XCTAssertEqual(clock.activeCount, 0)
  }
  @MainActor func testGradientValidatesProjectsAndHoldsBoundComponents() async throws {
    let clock = JoltClock.testClock()
    let scope = JoltScope()
    let lime = JoltColor(argb: 0xffdb_ff7a)
    let violet = JoltColor(argb: 0xff77_66ff)
    XCTAssertThrowsError(try JoltGradient(colors: [lime]))
    XCTAssertThrowsError(try JoltGradient(colors: Array(repeating: lime, count: 9)))
    XCTAssertThrowsError(try JoltGradient(colors: [lime, violet], stops: [0]))
    XCTAssertThrowsError(try JoltGradient(colors: [lime, violet], stops: [0, 1.2]))
    XCTAssertThrowsError(try JoltGradient(colors: [lime, violet], stops: [0.8, 0.2]))
    XCTAssertThrowsError(try JoltGradient(colors: [lime, violet], angle: .nan))
    let plain = try JoltGradient(colors: [lime, violet, lime])
    XCTAssertEqual(plain.frame.stops, [0, 0.5, 1])
    XCTAssertEqual(plain.frame.angle, 180)
    let angle = try scope.value(135, clock: clock)
    let stop = try scope.value(0.5, clock: clock)
    let progress = try scope.value(0, clock: clock)
    let tint = try scope.retain(JoltColorValue(progress, from: lime, to: violet))
    let gradient = try scope.retain(
      JoltGradient(
        colors: [.constant(lime), .value(tint), .constant(violet)],
        stops: [0.2, .value(stop), 1], angle: .value(angle)))
    XCTAssertEqual(gradient.frame.angle, 135)
    let view = UUID()
    gradient.link(view, active: true, reduced: false)
    XCTAssertTrue(gradient.following)
    try angle.animate(to: 315, transition: .tween(milliseconds: 1000, ease: .linear))
    try clock.advance(by: 500)
    XCTAssertEqual(gradient.frame.angle, 225, accuracy: 1e-6)
    XCTAssertEqual(gradient.settled.angle, 315)
    try stop.set(1.4)
    XCTAssertEqual(gradient.frame.stops, [0.2, 1, 1])
    try stop.set(-1)
    XCTAssertEqual(gradient.frame.stops, [0.2, 0.2, 1])
    try progress.set(1)
    XCTAssertEqual(gradient.frame.colors[1], violet)
    gradient.link(view, active: false, reduced: false)
    XCTAssertFalse(gradient.following)
    try stop.set(0.6)
    XCTAssertEqual(gradient.frame.stops, [0.2, 0.2, 1])
    gradient.link(view, active: true, reduced: false)
    XCTAssertEqual(gradient.frame.stops, [0.2, 0.6, 1])
    gradient.suspend()
    try progress.set(0)
    XCTAssertEqual(gradient.frame.colors[1], violet)
    gradient.pause()
    gradient.resume()
    XCTAssertFalse(gradient.following)
    gradient.play()
    XCTAssertEqual(gradient.frame.colors[1], lime)
    XCTAssertThrowsError(try gradient.update(colors: [.constant(lime), .constant(violet)]))
    XCTAssertThrowsError(try gradient.update(stops: [0, 0.5, 2]))
    XCTAssertEqual(gradient.frame.stops, [0.2, 0.6, 1])
    try gradient.update(stops: [0, 0.3, 1], angle: 90)
    XCTAssertEqual(gradient.frame.stops, [0, 0.3, 1])
    XCTAssertEqual(gradient.frame.angle, 90)
    gradient.unlink(view)
    XCTAssertFalse(gradient.following)
    scope.release(gradient)
    XCTAssertTrue(gradient.disposed)
    XCTAssertFalse(tint.disposed)
    XCTAssertThrowsError(try gradient.update(angle: 0))
    gradient.link(view, active: true, reduced: false)
    XCTAssertFalse(gradient.following)
    scope.dispose()
    XCTAssertEqual(clock.activeCount, 0)
  }
  @MainActor func testBlurUsesTheWebMeaningAndClampsBoundAmounts() async throws {
    let clock = JoltClock.testClock()
    XCTAssertThrowsError(try JoltBlur(radius: 0.5))
    XCTAssertThrowsError(try JoltBlur(radius: 65))
    XCTAssertThrowsError(try JoltBlur(amount: 1.2))
    XCTAssertThrowsError(try JoltBlur(amount: .constant(.nan)))
    let fixed = try JoltBlur(amount: 0.5)
    XCTAssertEqual(fixed.radius, 24)
    XCTAssertEqual(fixed.appliedRadius, 12)
    let amount = try JoltMotionValue(0, clock: clock)
    let blur = try JoltBlur(amount: .value(amount), radius: 40)
    let view = UUID()
    blur.link(view, active: true, reduced: false)
    try amount.animate(to: 1, transition: .spring(.bouncy))
    try clock.advance(by: 200)
    XCTAssertGreaterThan(blur.amount, 0)
    XCTAssertEqual(blur.settledAmount, 1)
    try amount.set(1.3)
    XCTAssertEqual(blur.appliedRadius, 40)
    try amount.set(-0.2)
    XCTAssertEqual(blur.amount, 0)
    blur.pause()
    try amount.set(0.25)
    XCTAssertEqual(blur.amount, 0)
    blur.play()
    XCTAssertEqual(blur.appliedRadius, 10)
    XCTAssertThrowsError(try blur.update(amount: -1))
    try blur.update(amount: 1)
    XCTAssertEqual(blur.appliedRadius, 40)
    blur.dispose()
    XCTAssertEqual(blur.appliedRadius, 0)
    XCTAssertFalse(amount.disposed)
    XCTAssertThrowsError(try blur.update(amount: 0))
    XCTAssertEqual(clock.activeCount, 0)
  }
