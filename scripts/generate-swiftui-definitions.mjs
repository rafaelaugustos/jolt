function transition(input) {
  if (input.type === 'spring') return { kind: 'spring', ...springPhysics(input) }
  const curve =
    typeof input.ease === 'string'
      ? timingCurves[input.ease]
      : (input.ease ?? timingCurves.easeOut)
  if (!Array.isArray(curve) || curve.length !== 4)
    throw Error('Unsupported SwiftUI preset easing')
  return { kind: 'tween', milliseconds: input.duration ?? 300, curve }
}
const literal = (value) => {
  if (!Number.isFinite(value)) throw Error('SwiftUI definitions must be finite')
  return String(value)
}
const array = (values) => `[${values.map(literal).join(', ')}]`
const swiftTransition = (input) => {
  const value = transition(input)
  return value.kind === 'spring'
    ? `.spring(mass: ${literal(value.mass)}, stiffness: ${literal(value.stiffness)}, damping: ${literal(value.damping)})`
    : `.tween(milliseconds: ${literal(value.milliseconds)}, curve: ${array(value.curve)})`
}
const cases = (entries, indent = '    ') =>
  entries
    .map(
      ([name, body]) =>
        `${indent}case .${name}:${body.startsWith('\n') ? '' : ' '}${body}`,
    )
    .join('\n')
const source = `// Generated by scripts/generate-swiftui-definitions.mjs from the shared Jolt recipes.
// Units: points on Apple, DIP on NativeScript, CSS px on the Web; degrees; milliseconds.

enum Definitions {
  static func curve(_ ease: JoltEase) -> [Double] {
    switch ease {
${cases(Object.entries(timingCurves).map(([name, curve]) => [name, array(curve)]))}
    }
  }
  static func spring(_ spring: JoltSpring) -> JoltTransition.Kind {
    switch spring {
${cases(Object.entries(springs).map(([name, value]) => [name, swiftTransition(value)]))}
    }
  }
  static func channels(_ preset: JoltPreset) -> [Channel] {
    switch preset {
${cases(
  names.map((name) => {
    const recipe = presets[name]
    const channels = Object.entries(recipe.keyframes).map(([property, frame]) => {
      if (
        !['x', 'y', 'scale', 'opacity'].includes(property) ||
        (Array.isArray(frame) && frame.length !== 2)
      )
        throw Error('Unsupported SwiftUI preset channel')
      const from = Array.isArray(frame) ? literal(frame[0]) : 'nil'
      const to = literal(Array.isArray(frame) ? frame[1] : frame)
      return `.init(.${property}, from: ${from}, to: ${to}, ${swiftTransition(recipe.transition[property] ?? recipe.transition)})`
    })
    return [name, `\n      [\n        ${channels.join(',\n        ')},\n      ]`]
  }),
)}
    }
  }
  struct Channel: Sendable {
    enum Property: Sendable { case x, y, scale, opacity }
    let property: Property
    let from: Double?
    let to: Double
    let kind: JoltTransition.Kind
    init(_ property: Property, from: Double?, to: Double, _ kind: JoltTransition.Kind) {
      self.property = property
      self.from = from
      self.to = to
      self.kind = kind
    }
  }
}
`
